import type { Metadata } from "next";
import { SITE } from "@/data/site";

/**
 * Absolute self-referencing canonical URL.
 * Home uses a trailing slash to match the URL Next actually serves;
 * every other path has no trailing slash.
 */
export function canonicalFor(path: string = "/"): string {
  const base = SITE.url.replace(/\/$/, "");
  if (!path || path === "/") {
    return `${base}/`;
  }
  const normalized = (path.startsWith("/") ? path : `/${path}`).replace(/\/$/, "");
  return `${base}${normalized}`;
}

/** Stable site logo — always crawlable static asset. */
export function siteLogoUrl(): string {
  return `${SITE.url.replace(/\/$/, "")}/invoice_logo.png`;
}

/** Absolute URL for a path under the site origin. */
export function absoluteUrl(path: string): string {
  return canonicalFor(path === "/" ? "/" : path);
}

/** Default 1200×630 share image generated by src/app/opengraph-image.tsx */
export function defaultShareImage(alt?: string) {
  return {
    url: absoluteUrl("/opengraph-image"),
    width: 1200,
    height: 630,
    alt: alt ?? `${SITE.name}: Free Invoice Generator`,
  };
}

type SocialOpts = {
  title: string;
  description: string;
  url: string;
  type?: "website" | "article";
  /** Absolute image URL; defaults to site opengraph-image */
  imageUrl?: string;
  imageAlt?: string;
  publishedTime?: string;
  modifiedTime?: string;
  authors?: string[];
};

/** Consistent Open Graph + Twitter card block for every page. */
export function pageSocial(opts: SocialOpts): Pick<Metadata, "openGraph" | "twitter"> {
  const image = {
    url: opts.imageUrl ?? defaultShareImage().url,
    width: 1200,
    height: 630,
    alt: opts.imageAlt ?? opts.title,
  };

  return {
    openGraph: {
      title: opts.title,
      description: opts.description,
      type: opts.type ?? "website",
      url: opts.url,
      siteName: SITE.name,
      images: [image],
      ...(opts.publishedTime ? { publishedTime: opts.publishedTime } : {}),
      ...(opts.modifiedTime ? { modifiedTime: opts.modifiedTime } : {}),
      ...(opts.authors ? { authors: opts.authors } : {}),
    },
    twitter: {
      card: "summary_large_image",
      title: opts.title,
      description: opts.description,
      images: [image.url],
    },
  };
}

/**
 * hreflang cluster for the main generator + country variants.
 * All pages in the set should share the same map.
 */
export function localeLanguageAlternates(): NonNullable<Metadata["alternates"]>["languages"] {
  return {
    "x-default": canonicalFor("/invoice-generator"),
    en: canonicalFor("/invoice-generator"),
    "en-PK": canonicalFor("/invoice-generator/pakistan"),
    "en-AE": canonicalFor("/invoice-generator/uae"),
    "en-GB": canonicalFor("/invoice-generator/uk"),
    "en-US": canonicalFor("/invoice-generator/usa"),
  };
}

/** Free web-app offer. Kept minimal: no shipping or return policy, which do not apply to a free browser tool. */
export function digitalOffer(options: {
  url: string;
  priceCurrency?: string;
  price?: string | number;
}) {
  return {
    "@type": "Offer" as const,
    url: options.url,
    price: String(options.price ?? "0"),
    priceCurrency: options.priceCurrency ?? "USD",
    availability: "https://schema.org/InStock",
  };
}

/** Image list Google can crawl for Product / SoftwareApplication. */
export function schemaImages(...urls: (string | undefined)[]) {
  const logo = siteLogoUrl();
  const unique = [...new Set(urls.filter(Boolean) as string[])];
  if (!unique.includes(logo)) unique.push(logo);
  return unique;
}

/** Publisher block for BlogPosting / Article JSON-LD. */
export function publisherOrg() {
  return {
    "@type": "Organization" as const,
    name: SITE.operator,
    url: SITE.url,
    logo: {
      "@type": "ImageObject" as const,
      url: siteLogoUrl(),
    },
  };
}
